-- 10. DIAGNOSTIC RESULT (Shows counts in SQL Editor)
SELECT 
    (SELECT COUNT(*) FROM public.softcreation_users) AS total_users,
    (SELECT COUNT(*) FROM public.softcreation_vouchers) AS total_vouchers,
    (SELECT COUNT(*) FROM public.softcreation_logs) AS total_logs;

