-- 1. ENSURE EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. CREATE / UPDATE 'softcreation_users' TABLE
CREATE TABLE IF NOT EXISTS public.softcreation_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    username TEXT,
    role TEXT DEFAULT 'User',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CREATE / UPDATE 'softcreation_vouchers' TABLE
CREATE TABLE IF NOT EXISTS public.softcreation_vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_no TEXT UNIQUE NOT NULL,
    date TEXT NOT NULL,
    type TEXT NOT NULL,
    bank TEXT NOT NULL,
    amount NUMERIC NOT NULL DEFAULT 0,
    note TEXT,
    bill_url TEXT DEFAULT 'No Bill',
    status TEXT DEFAULT 'PENDING',
    user_email TEXT NOT NULL,
    hidden_data JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for lightning-fast queries and pagination
CREATE INDEX IF NOT EXISTS idx_vouchers_status ON public.softcreation_vouchers(status);
CREATE INDEX IF NOT EXISTS idx_vouchers_date ON public.softcreation_vouchers(date);
CREATE INDEX IF NOT EXISTS idx_vouchers_user_email ON public.softcreation_vouchers(user_email);
CREATE INDEX IF NOT EXISTS idx_vouchers_voucher_no ON public.softcreation_vouchers(voucher_no);

-- 4. CREATE / UPDATE 'softcreation_logs' (AUDIT TRAIL)
CREATE TABLE IF NOT EXISTS public.softcreation_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email TEXT,
    action TEXT NOT NULL,
    voucher_no TEXT,
    details TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. CREATE / UPDATE 'softcreation_settings'
CREATE TABLE IF NOT EXISTS public.softcreation_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_by TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Seed default settings
INSERT INTO public.softcreation_settings (key, value)
VALUES ('MAINTENANCE_MODE', 'OFF')
ON CONFLICT (key) DO NOTHING;

-- 6. GRANT FULL PERMISSIONS TO 'anon' & 'authenticated' ROLES
-- (This resolves the issue where queries return 0 records / empty lists)
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;

-- 7. CONFIGURE ROW LEVEL SECURITY (RLS) POLICIES
-- We enable open access policies for the application's browser client
ALTER TABLE public.softcreation_users ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow anon read users" ON public.softcreation_users;
CREATE POLICY "Allow anon read users" ON public.softcreation_users FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Allow anon insert users" ON public.softcreation_users;
CREATE POLICY "Allow anon insert users" ON public.softcreation_users FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

ALTER TABLE public.softcreation_vouchers ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow anon all vouchers" ON public.softcreation_vouchers;
CREATE POLICY "Allow anon all vouchers" ON public.softcreation_vouchers FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

ALTER TABLE public.softcreation_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow anon all logs" ON public.softcreation_logs;
CREATE POLICY "Allow anon all logs" ON public.softcreation_logs FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

ALTER TABLE public.softcreation_settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow anon all settings" ON public.softcreation_settings;
CREATE POLICY "Allow anon all settings" ON public.softcreation_settings FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- 8. CONFIGURE SUPABASE STORAGE BUCKET FOR BILL RECEIPTS ('voucher-bills')
INSERT INTO storage.buckets (id, name, public)
VALUES ('voucher-bills', 'voucher-bills', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS policies for uploading and reading receipts
DROP POLICY IF EXISTS "Public Access voucher-bills" ON storage.objects;
CREATE POLICY "Public Access voucher-bills" ON storage.objects FOR SELECT TO anon, authenticated USING (bucket_id = 'voucher-bills');

DROP POLICY IF EXISTS "Public Upload voucher-bills" ON storage.objects;
CREATE POLICY "Public Upload voucher-bills" ON storage.objects FOR INSERT TO anon, authenticated WITH CHECK (bucket_id = 'voucher-bills');

DROP POLICY IF EXISTS "Public Update voucher-bills" ON storage.objects;
CREATE POLICY "Public Update voucher-bills" ON storage.objects FOR UPDATE TO anon, authenticated USING (bucket_id = 'voucher-bills');

